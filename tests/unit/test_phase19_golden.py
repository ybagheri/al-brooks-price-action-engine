def test_golden_breakout_001_takes_its_reference_from_the_range_not_from_a_swing() -> None:
    """The reference is bar 28's high of 106.2, not the 106.0 the flat bars share.

    A flat series produces no confirmed swings, so the N-bar reference is the only
    one available, and the window ends one bar *before* the breakout bar. Pinning
    both is what stops the reference from being quietly taken from the wrong
    window.
    """
    golden = ALL["golden_breakout_001"]
    bars = golden.bars
    setup = golden.setup("BREAKOUT")
    tol = 0.10 * golden.expected["atr"]

    assert golden.analyze().swings == [], "a flat series must produce no swings"
    assert setup["reference_price"] == pytest.approx(max(row["h"] for row in bars[9:29]))
    assert setup["reference_price"] == pytest.approx(bars[28]["h"])
    assert setup["ref_is_swing"] is False
    assert setup["reference_kind"] == "N_BAR"
    assert bars[29]["c"] > setup["reference_price"] + tol


def test_golden_breakout_001_is_unresolved_because_nothing_follows_it() -> None:
    """`BREAKOUT` and `PENDING`, not a resolved state.

    A `FOLLOW_THROUGH` or `FAILED` here would be a statement about a bar that does
    not exist, and the whole point of the closed-bar contract is that it cannot be.
    """
    golden = ALL["golden_breakout_001"]
    setup = golden.setup("BREAKOUT")

    assert setup["state"] == "BREAKOUT"
    assert setup["outcome"] == "PENDING"
    assert setup["decide_bar"] == -1
    assert setup["breakout_bar"] == golden.last_closed
    assert golden.last_closed == len(golden.bars) - 1


