@dataclass(frozen=True)
class Golden:
    """One fixture: its bars, the config it was authored against, and its claims."""

    id: str
    concept: str
    question: str
    config: dict[str, Any]
    last_closed: int
    bars: tuple[dict[str, float], ...]
    expected: dict[str, Any]
    must_not: dict[str, str]
    falsifiers: tuple[dict[str, str], ...]
    raw: dict[str, Any]

    @property
    def series(self) -> BarSeries:
        return BarSeries(list(self.bars))

    @property
    def analyzer_config(self) -> AnalyzerConfig:
        return AnalyzerConfig(**self.config)

    def analyze(self, bars: list[dict[str, float]] | None = None,
                last_closed: int | None = None) -> AnalysisResult:
        cfg = self.analyzer_config
        source = self.bars if bars is None else tuple(bars)
        return Analyzer(cfg).analyze(
            BarSeries(list(source)),
            last_closed=self.last_closed if last_closed is None else last_closed,
        )

    def setup(self, detector: str, result: AnalysisResult | None = None) -> dict[str, Any]:
        """The finding for `detector`, or a failure that says what was found."""
        found = result.setups if result is not None else self.analyze().setups
        for entry in found:
            if entry.get("detector") == detector:
                return entry
        raise AssertionError(
            f"{self.id}: no finding for {detector}; the run produced "
            f"{[e.get('detector') for e in found]}"
        )

    def decision(self, result: AnalysisResult | None = None) -> dict[str, Any]:
        return (result or self.analyze()).decision


def load(golden_id: str) -> Golden:
    """Read one fixture from disk."""
    path = GOLDEN_DIR / f"{golden_id}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    bars = tuple(
        {k: float(v) for k, v in row.items() if k in ("o", "h", "l", "c")}
        for row in data["bars"]
    )
    return Golden(
        id=data["id"],
        concept=data["concept"],
        question=data["question"],
        config=data["config"],
        last_closed=int(data["last_closed"]),
        bars=bars,
        expected=data["expected"],
        must_not=data["must_not"],
        falsifiers=tuple(data.get("falsifiers", ())),
        raw=data,
    )


ALL = {gid: load(gid) for gid in FIXTURE_IDS}


