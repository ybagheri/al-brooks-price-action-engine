def wilder_atr(bars: tuple[dict[str, float], ...], period: int, at: int) -> float:
    """ATR at bar `at`, from Wilder's smoothing, written from the definition.

    Deliberately not a call into `calculate_atr_series`. A golden that pins an ATR
    it obtained by calling the function it is testing is circular, and this is
    the one value in every fixture that could not be hand-derived comfortably. If
    the engine's ATR were wrong, this disagrees with it.

    True range is `max(high-low, |high-prev_close|, |low-prev_close|)`, with the
    first bar using `high-low`, and the average is Wilder's: seed with the mean of
    the first `period` true ranges, then `prev + (tr - prev) / period`.
    """
    trs: list[float] = []
    for i, row in enumerate(bars[: at + 1]):
        if i == 0:
            trs.append(row["h"] - row["l"])
            continue
        prev = bars[i - 1]["c"]
        trs.append(
            max(row["h"] - row["l"], abs(row["h"] - prev), abs(row["l"] - prev))
        )
    if len(trs) < period:
        raise AssertionError(f"need {period} true ranges, have {len(trs)}")
    value = sum(trs[:period]) / period
    for tr in trs[period:]:
        value += (tr - value) / period
    return value


