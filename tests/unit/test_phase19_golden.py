def test_a_pullback_plan_is_its_extreme_plus_the_declared_buffer() -> None:
    """The formula, not the numbers. ATR appears on both sides, so this holds for
    any ATR and only tests what it should."""
    golden = ALL["golden_h2_001"]
    cfg = golden.analyzer_config
    result = golden.analyze()
    plan = result.decision["plan"]
    atr = golden.expected["atr"]

    assert plan["stop"] == pytest.approx(
        plan["stop_reference"] - cfg.plan_stop_buffer_atr * atr
    )
    assert plan["stop_reference"] == pytest.approx(
        result.decision["plan"]["stop_reference"]
    )
    assert plan["target"] == pytest.approx(plan["entry"] + cfg.plan_fallback_target_atr * atr)
    assert plan["reward_to_risk"] == pytest.approx(
        (plan["target"] - plan["entry"]) / (plan["entry"] - plan["stop"])
    )
    assert plan["has_structural_stop"] is True


def test_a_reversal_plan_always_has_exactly_twice_the_fallback_risk() -> None:
    """A consequence of the family having no levels, and worth pinning as a
    property rather than a coincidence: reward is 2.0*atr and risk is 1.0*atr."""
    golden = ALL["golden_mtr_001"]
    cfg = golden.analyzer_config
    plan = golden.analyze().decision["plan"]
    atr = golden.expected["atr"]

    assert plan["entry"] == pytest.approx(plan["entry_reference"])
    assert plan["stop"] == pytest.approx(plan["entry"] - cfg.plan_fallback_stop_atr * atr)
    assert plan["target"] == pytest.approx(plan["entry"] + cfg.plan_fallback_target_atr * atr)
    assert plan["reward_to_risk"] == pytest.approx(
        cfg.plan_fallback_target_atr / cfg.plan_fallback_stop_atr
    )
    assert plan["has_structural_stop"] is False


def test_a_projected_target_is_the_pullback_low_plus_the_measured_leg() -> None:
    """`target = B0 + (A1 - A0)`, read off the three swings in the bars.

    The whole arithmetic of a measured move, from three prices a chart reader can
    see, with no engine output involved.
    """
    golden = ALL["golden_fm_001"]
    bars = golden.bars
    a0 = min(row["l"] for row in bars[9:16])
    a1 = max(row["h"] for row in bars[16:21])
    b0 = min(row["l"] for row in bars[20:25])
    move = next(m for m in golden.analyze().measured_moves if m["family"] == "REGULAR")

    assert a0 == pytest.approx(95.8)
    assert a1 == pytest.approx(106.1)
    assert b0 == pytest.approx(100.8)
    assert move["mm_range"] == pytest.approx(a1 - a0)
    assert move["target_price"] == pytest.approx(b0 + a1 - a0)
    assert move["pullback_depth"] == pytest.approx((a1 - b0) / (a1 - a0))
    assert golden.expected["measured_move"]["target_price"] == pytest.approx(
        move["target_price"]
    )


def test_a_reversal_score_is_a_multiple_of_twenty_five_and_names_what_is_missing() -> None:
    """The score is a count of legs. Anything else would be a claim about
    probability, and a golden that let a non-multiple through would be the first
    place that showed up."""
    for gid in ("golden_mtr_001", "golden_double_001"):
        golden = ALL[gid]
        result = golden.analyze()
        for entry in result.setups:
            if entry.get("setup_family") != "REVERSAL":
                continue
            assert entry["score"] % 25 == 0, f"{gid}: {entry['score']}"
            assert entry["score"] == 25 * sum(
                [entry["ema_break"], entry["retest"], entry["bo_follow"], entry["pressure_ok"]]
            )
            assert (entry["verdict"] == "MAJOR") == (entry["score"] == 100)
            assert (entry["verdict"] == "MINOR") == (0 < entry["score"] < 100)


