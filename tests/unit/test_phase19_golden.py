def test_golden_h2_001_places_the_legs_where_the_bars_put_them() -> None:
    """Bar by bar, from the fixture's own chart description.

    The derivation is that bars 40..48 share a flat high of 114.0, so the first
    higher high in the window is bar 50; that the level reached up to bar 50 is
    its low of 112.5, so bar 51's 112.4 is the deeper low; and that bar 52's high
    of 114.5 exceeds bar 51's 114.2. Each of those is checked against the bars.
    """
    golden = ALL["golden_h2_001"]
    bars = golden.bars
    setup = golden.setup("PULLBACK_H")

    assert len({bars[i]["h"] for i in range(40, 49)}) == 1, "bars 40..48 must share one high"
    assert bars[50]["h"] > max(bars[i]["h"] for i in range(41, 50))
    assert bars[51]["l"] < min(bars[i]["l"] for i in range(40, 51))
    assert bars[52]["h"] > bars[51]["h"]

    assert setup["anchor_bar"] == 50
    assert setup["extreme_bar"] == 51
    assert setup["signal_bar"] == 52
    assert setup["reference_price"] == pytest.approx(bars[52]["h"])
    assert setup["extreme_price"] == pytest.approx(bars[51]["l"])


