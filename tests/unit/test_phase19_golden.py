def test_every_golden_bar_is_a_bar_the_engine_will_accept() -> None:
    """`BarSeries` rejects an open outside `[low, high]`.

    This test is here because of a real defect it would have caught. The Phase 6
    H2 fixture uses `mk(201, 200, 187, 192)` — an open above its own high. It
    passes, because `detect_h1_h2` reads raw dicts and never constructs a `Bar`.
    A golden fixture has to survive the whole pipeline, so a bar that only works
    when read loosely is not admissible.
    """
    for golden in ALL.values():
        series = golden.series  # raises on a malformed bar
        assert len(series) == len(golden.bars)
        for i, row in enumerate(series):
            assert row.low <= min(row.open, row.close), (
                f"{golden.id} bar {i}: open or close below the low"
            )
            assert max(row.open, row.close) <= row.high, (
                f"{golden.id} bar {i}: open or close above the high"
            )


def test_atr_is_recomputed_from_the_bars() -> None:
    """Independent re-derivation of the one value a fixture cannot hand-check.

    The engine's `calculate_atr_series` and the local implementation here are two
    readings of Wilder's definition. They agree, so the ATR pinned in the fixtures
    is a property of the bars rather than a property of the code.
    """
    for golden in ALL.values():
        expected = golden.expected["atr"]
        mine = wilder_atr(golden.bars, golden.analyzer_config.atr_period, golden.last_closed)
        assert mine == pytest.approx(expected, rel=1e-9), (
            f"{golden.id}: hand-rolled ATR {mine!r} against pinned {expected!r}"
        )
        theirs = calculate_atr_series(golden.series, period=golden.analyzer_config.atr_period)
        assert theirs[golden.last_closed] == pytest.approx(expected, rel=1e-12)


