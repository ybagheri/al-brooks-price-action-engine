MUST_NOT_CHECKS: dict[str, Callable[[Golden, AnalysisResult], bool]] = {
    "a_confirmed_first_entry_somewhere_in_the_run": lambda g, r: not any(
        e.get("setup_type") == "H1" and e.get("state") == "CONFIRMED" for e in r.setups
    ),
    "the_plan_stops_on_an_atr_fallback": lambda g, r: (
        r.decision["plan"]["stop_basis"] != "ATR_FALLBACK"
    ),
    "the_decision_is_an_abstention": lambda g, r: r.decision["action"] not in (
        "WAIT",
        "NO_TRADE",
    ),
    "the_reference_is_reported_as_a_swing": lambda g, r: all(
        not e.get("ref_is_swing") for e in r.setups if e.get("detector") == "BREAKOUT"
    ),
    "the_outcome_is_reported_as_resolved": lambda g, r: all(
        e.get("outcome") == "PENDING"
        for e in r.setups
        if e.get("detector") == "BREAKOUT"
    ),
    "the_verdict_is_major": lambda g, r: all(
        e.get("verdict") != "MAJOR" for e in r.setups if e.get("setup_family") == "REVERSAL"
    ),
    "the_score_is_not_a_multiple_of_twenty_five": lambda g, r: all(
        e.get("score", 0) % 25 == 0 for e in r.setups if e.get("setup_family") == "REVERSAL"
    ),
    "the_plan_claims_a_structural_stop": lambda g, r: (
        r.decision["plan"] is None or r.decision["plan"]["has_structural_stop"] is False
    ),
    "the_ranked_subject_is_a_double": lambda g, r: "DOUBLE" not in r.decision["subject"],
    "the_context_fields_are_populated": lambda g, r: all(
        e.get("level") == 0.0 and not e.get("is_tested")
        for e in r.setups
        if "DOUBLE" in str(e.get("setup_family"))
    ),
    "the_pipeline_reports_a_developed_state": lambda g, r: all(
        e.get("state") == "PROJECTED"
        for e in r.setups
        if e.get("setup_family") == "FADING_MEASURED_MOVE"
    ),
    "the_fade_becomes_the_ranked_answer": lambda g, r: r.decision["subject"] not in (
        "MEASURED_MOVE",
        "FADING_MEASURED_MOVE",
    ),
    "the_projection_is_called_inverse": lambda g, r: all(
        m["family"] != "INVERSE" for m in r.measured_moves
    ),
}


