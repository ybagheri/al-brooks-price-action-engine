"""The golden validation dataset (Phase 19).

## What a golden fixture is, and what it deliberately is not

It is **not** a snapshot of the engine's output. That is the failure mode a
"golden file" suite drifts into, and it is worth being precise about why it is
worthless here: a snapshot of `AnalysisResult.to_dict()` cannot tell a fix from a
regression. It fails on both, it passes on neither, and the only way to update it
is to run the code and paste what it said. After one such update nobody can read
the file and know whether the change was right.

So each fixture here is three things:

1. **Hand-authored bars.** Not generated by the code under test, and not
   transcribed from it — `BarSeries` validates them, which is a real check.
2. **A hand-derived expectation**, with a `basis` string for every single value
   saying how it follows from the bars and the documented gates. A value with no
   basis is a test failure, so a fixture cannot quietly become a dump.
3. **A list of falsifiers** — perturbations whose effect the derivation
   *predicts*. This is the part a snapshot structurally cannot do, and it is the
   reason the suite has teeth: remove the resumption bar from the H2 and the
   derivation says the state must drop to `PROVISIONAL`, and that is checked.

There is one place where provenance has to be stated rather than proved, and it
is stated rather than hidden. ATR is computed by Wilder smoothing over a 14-bar
window, which is checkable by hand but tedious, so the fixtures **pin** the value
it produces. To stop that from being circular, `test_atr_is_recomputed_from_the_bars`
re-derives ATR from the fixture's own bars with an independent implementation and
asserts the two agree. Everything downstream of ATR in a fixture is expressed as a
*formula* — `stop = extreme_price - 0.25 * atr` — and the test evaluates the
formula, so the structural claim is ATR-independent.

## What this suite is not

**It is not statistical validation.** Every fixture here is a statement about
*detection semantics*: given these bars, does the engine name what the chart
shows, and does it refuse the trades it should refuse. Nothing here says a setup
works, has an edge, or will continue. `docs/algorithms/VALIDATION.md` says the
same thing at length, and the one test that guards it is
`test_no_golden_decision_claims_to_be_a_probability`.

Two things this dataset found on its first run, both recorded in the fixtures and
in `VALIDATION.md`:

- **`golden_fm_001`: the fade lifecycle is unreachable through the pipeline.** The
  registry calls `create_setups`, which only seeds, so a live consumer sees
  `PROJECTED` / `age 0` forever and `track_fading_measured_moves` — the function
  that advances the state — is never called by the engine. The fixture records
  both readings, because recording only the flattering one would make the dataset
  a whitewash.
- **`golden_h2_001`'s window depends on `max_pb_bars`, not on the market.** The
  detector calls *the first bar with a higher high* the first leg, so in a clean
  uptrend the "pullback" is just the next up-bar and the window is a choice about
  configuration, not a reading of price. The fixture pins `max_pb_bars` and
  supplies a flat top, which is what makes a higher high meaningful. That is a
  property of the detector worth stating rather than hiding.
"""

